    "help",
    "帮助",
    "使用说明",
    "怎么用",
    "如何使用",
    "你能做什么",
    "能做什么",
    "有什么功能",
    "功能介绍",
    "我可以问什么",
    "可以问什么",
    "介绍一下这个系统",
    "介绍一下你",
